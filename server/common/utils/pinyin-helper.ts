/**
 * 获取姓名的拼音首字母（小写，去掉空格）
 * 每个汉字取拼音首字母；生僻字/非汉字字符：字母保留小写，数字保留，其他字符用下划线代替
 */
export function getPinyinInitials(name: string): string {
  if (!name) return '';
  const cleanName = name.replace(/\s+/g, '');
  let result = '';
  for (const char of cleanName) {
    const initial = PINYIN_INITIALS[char];
    if (initial) {
      result += initial;
    } else if (/[a-zA-Z]/.test(char)) {
      result += char.toLowerCase();
    } else if (/[0-9]/.test(char)) {
      result += char;
    } else {
      result += '_';
    }
  }
  // 连续下划线合并，去掉首尾下划线
  result = result.replace(/_+/g, '_').replace(/^_+|_+$/g, '');
  return result;
}

/**
 * 获取初始密码：姓名拼音首字母 + '123456'
 */
export function getInitialPassword(name: string): string {
  const initials = getPinyinInitials(name);
  return `${initials}123456`;
}
